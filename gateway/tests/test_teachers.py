"""The teacher allowlist is a legal boundary, so it is tested like one.

Artemis is sold. A corpus generated by a model whose licence forbids training on
its output is a contract breach sitting inside the asset, and it is invisible
once the weights exist. These tests pin the refusals by name.
"""
import json

import pytest

from artemis.teachers import (
    REFUSED, TEACHERS, TeacherRefused, acceptable, assert_permitted, build_row,
    dedupe, load_seed_prompts,
)


def test_allowlist_is_permissive_only():
    """Every approved teacher is Apache-2.0 or MIT: licences that permit training on output."""
    assert TEACHERS, "the allowlist must not be empty"
    assert set(TEACHERS.values()) <= {"apache-2.0", "mit"}


@pytest.mark.parametrize("model_id", sorted(TEACHERS))
def test_permitted_teachers_return_their_licence(model_id):
    assert assert_permitted(model_id) == TEACHERS[model_id]


@pytest.mark.parametrize("model_id", [
    "Qwen/Qwen2.5-72B-Instruct",          # qwen licence, user threshold
    "meta-llama/Llama-3.3-70B-Instruct",  # forbids training non-Llama models
    "google/gemma-2-27b-it",              # AUP restricts competitive distillation
    "deepseek-ai/DeepSeek-R1",            # MIT, but will not fit 8x80GB
])
def test_named_refusals_explain_themselves(model_id):
    with pytest.raises(TeacherRefused) as e:
        assert_permitted(model_id)
    # The message has to carry the reason, or the next person just adds it back.
    assert len(str(e.value)) > len(model_id) + 40


@pytest.mark.parametrize("model_id", [
    "grok-4.7", "xai/grok-2", "openai/gpt-4o", "anthropic/claude-opus",
    "gemini-2.0-pro", "cohere/command-r",
])
def test_hosted_providers_are_refused(model_id):
    """No hosted provider is a teacher, whatever it is called or how it is spelled."""
    with pytest.raises(TeacherRefused):
        assert_permitted(model_id)


def test_unknown_model_is_refused_not_assumed():
    with pytest.raises(TeacherRefused) as e:
        assert_permitted("some-org/brand-new-model")
    assert "LICENCE" in str(e.value) or "licence" in str(e.value).lower()


# --- seed prompts ---------------------------------------------------------

def test_seeds_must_name_their_source(tmp_path):
    p = tmp_path / "seeds.jsonl"
    p.write_text(json.dumps({"prompt": "Explain a deadlock."}) + "\n")
    with pytest.raises(ValueError, match="source"):
        load_seed_prompts(p)


def test_seeds_drop_exact_duplicates(tmp_path):
    p = tmp_path / "seeds.jsonl"
    rows = [{"prompt": "Explain a deadlock.", "source": "handwritten"},
            {"prompt": "explain   a DEADLOCK.", "source": "handwritten"},
            {"prompt": "Explain a race condition.", "source": "handwritten"}]
    p.write_text("".join(json.dumps(r) + "\n" for r in rows))
    assert len(load_seed_prompts(p)) == 2


def test_empty_seed_file_is_an_error(tmp_path):
    p = tmp_path / "seeds.jsonl"
    p.write_text("\n\n")
    with pytest.raises(ValueError):
        load_seed_prompts(p)


# --- answer quality -------------------------------------------------------

def test_refusals_are_not_training_data():
    """Training on refusals teaches Artemis to refuse.

    Long enough to clear the length gate, so this exercises the refusal check
    rather than passing for the wrong reason.
    """
    for text in [
        "I can't help with that request, but I'd be glad to talk through the "
        "general principles involved instead.",
        "As an AI language model, I am unable to answer this one directly, "
        "though I can point you at the documentation.",
        "I'm sorry, but I cannot assist with that particular task. Perhaps try "
        "rephrasing what you are trying to accomplish.",
    ]:
        ok, why = acceptable(text)
        assert not ok and why == "refusal", text


def test_a_short_refusal_is_dropped_for_either_reason():
    """Whichever gate fires first, a two-word refusal never reaches training."""
    assert acceptable("I can't.")[0] is False


def test_short_and_empty_answers_are_dropped():
    assert acceptable("")[0] is False
    assert acceptable("Sure.")[0] is False


def test_repetitive_output_is_dropped():
    ok, why = acceptable("\n".join(["the same line"] * 40))
    assert not ok and why == "repetitive"


def test_a_real_answer_is_kept():
    ok, why = acceptable(
        "A deadlock happens when two threads each hold a lock the other needs.\n"
        "Break it by always acquiring locks in a fixed global order, or by using\n"
        "a timeout on acquisition so one side backs off and retries.")
    assert ok and why == ""


# --- row shape ------------------------------------------------------------

def test_build_row_records_full_provenance():
    seed = {"prompt": "Explain a deadlock.", "source": "handwritten-2026-10",
            "allowed_tools": [], "domain": None}
    row = build_row(seed, "  Two threads, two locks, opposite order.  ",
                    "Qwen/Qwen2.5-32B-Instruct", "apache-2.0")
    assert row["synthetic"] is True
    assert row["teacher"] == "Qwen/Qwen2.5-32B-Instruct"
    assert row["teacher_license"] == "apache-2.0"
    assert row["prompt_source"] == "handwritten-2026-10"
    assert row["messages"][0]["role"] == "user"
    assert row["messages"][-1]["role"] == "assistant"
    assert row["messages"][-1]["content"] == "Two threads, two locks, opposite order."


def test_dedupe_keeps_first_and_counts_drops(tmp_path):
    """An ensemble agrees often; training on one answer four times just reweights it."""
    p = tmp_path / "rows.jsonl"
    seed = {"prompt": "q", "source": "s"}
    rows = [build_row(seed, "Same answer, written out at length." * 2, m, TEACHERS[m])
            for m in list(TEACHERS)[:2]]
    rows.append(build_row(seed, "A genuinely different answer here." * 2,
                          "Qwen/Qwen2.5-32B-Instruct", "apache-2.0"))
    p.write_text("".join(json.dumps(r) + "\n" for r in rows))

    stats = dedupe(p)
    assert stats == {"kept": 2, "dropped": 1}
    kept = [json.loads(l) for l in p.read_text().splitlines() if l.strip()]
    assert kept[0]["teacher"] == list(TEACHERS)[0]   # first occurrence wins


def test_refused_table_covers_the_known_traps():
    """Documented refusals must stay documented; silence is how one creeps back."""
    joined = " ".join(REFUSED).lower()
    for marker in ("llama", "gemma", "grok"):
        assert marker in joined
